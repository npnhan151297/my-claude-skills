#!/bin/bash
# Embed a Google Font (latin, latin-ext, vietnamese) into src/gap/fonts.css as base64 @font-face,
# so renders never wait on a network or a font-load promise.
# Usage (from the Remotion project root): fetch-font.sh "Plus Jakarta Sans" "400;500;600;700"
set -euo pipefail
FAMILY="$1"; WEIGHTS="$2"
mkdir -p src/gap
UA="Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 Chrome/120 Safari/537.36"
Q=$(printf '%s' "$FAMILY" | sed 's/ /+/g')
TMP=$(mktemp -d)
curl -sSL -A "$UA" "https://fonts.googleapis.com/css2?family=${Q}:wght@${WEIGHTS}&display=block" -o "$TMP/in.css"
python3 -I - "$TMP" > src/gap/fonts.css <<'PY'
import base64, re, subprocess, sys, os
tmp = sys.argv[1]; css = open(os.path.join(tmp, "in.css")).read()
seen = {}
for subset, block in re.findall(r"/\*\s*([\w-]+)\s*\*/\s*@font-face\s*{([^}]*)}", css):
    if subset not in ("latin", "latin-ext", "vietnamese"):
        continue
    url = re.search(r"url\((https://[^)]+)\)", block).group(1)
    w = int(re.search(r"font-weight:\s*(\d+)", block).group(1))
    fam = re.search(r"font-family:\s*([^;]+);", block).group(1)
    rng = re.search(r"unicode-range:\s*([^;]+);", block).group(1)
    f = seen.setdefault(url, {"fam": fam, "rng": rng, "lo": w, "hi": w})
    f["lo"], f["hi"] = min(f["lo"], w), max(f["hi"], w)
print("/* Generated by fetch-font.sh. Do not edit. */")
for url, f in seen.items():
    path = os.path.join(tmp, os.path.basename(url))
    subprocess.run(["curl", "-sSL", url, "-o", path], check=True)
    data = base64.b64encode(open(path, "rb").read()).decode()
    print(f"@font-face {{ font-family: {f['fam']}; font-style: normal; font-weight: {f['lo']} {f['hi']}; font-display: block;\n"
          f"  src: url(data:font/woff2;base64,{data}) format('woff2'); unicode-range: {f['rng']}; }}")
PY
rm -rf "$TMP"
echo "Wrote src/gap/fonts.css ($(grep -c '@font-face' src/gap/fonts.css) faces, $(du -k src/gap/fonts.css | cut -f1) KB)"
